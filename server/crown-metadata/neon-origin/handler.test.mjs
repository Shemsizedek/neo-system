import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile, rm} from 'node:fs/promises';
import {buildCrownOrigin} from './build.mjs';

test('Neon Crown origin serves exact NOMNI JSON paths with HTTP 200 and no redirect',async(t)=>{
  const out=new URL('./dist/verify-local.mjs',import.meta.url);
  t.after(()=>rm(out,{force:true}));
  const result=await buildCrownOrigin(out);
  assert.equal(result.imageSha256,'00472d01de84f4d876d7cd6ca1fa53a844a0b7929f93f97cd5dfb4c28e7bb7e6');
  const app=(await import(out.href)).default;
  const canonical='https://crown.holytemples.org/assets/NOMNI/';
  const m=await app.fetch(new Request(canonical+'tokenscan.json'));
  assert.equal(m.status,200);
  assert.match(m.headers.get('content-type'),/^application\/json/);
  assert.equal(m.headers.get('location'),null);
  assert.equal(m.headers.get('access-control-allow-origin'),'*');
  const data=await m.json();
  assert.equal(data.asset,'NOMNI');
  assert.equal(data.name,'NOMNI');
  const info=await app.fetch(new Request(canonical+'info.json'));
  assert.equal(info.status,200);
  assert.deepEqual(await info.json(),data);
  const bill=await app.fetch(new Request(canonical+'bill-1.json'));
  assert.equal(bill.status,200);
  const record=await bill.json();
  assert.equal(record.token.asset_id,'6195210');
  const image=await app.fetch(new Request(canonical+'nomni-bill-1.jpg'));
  assert.equal(image.status,200);
  assert.equal(image.headers.get('content-type'),'image/jpeg');
  const bytes=Buffer.from(await image.arrayBuffer());
  assert.equal(bytes.length,215295);
  assert.equal(createHash('sha256').update(bytes).digest('hex'),record.sha256);
  const head=await app.fetch(new Request(canonical+'tokenscan.json',{method:'HEAD'}));
  assert.equal(head.status,200);
  assert.equal(await head.text(),'');
  const disallowed=await app.fetch(new Request(canonical+'tokenscan.json',{method:'POST'}));
  assert.equal(disallowed.status,405);
  const missing=await app.fetch(new Request(canonical+'missing.json'));
  assert.equal(missing.status,404);
});
